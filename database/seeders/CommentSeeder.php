<?php

namespace Database\Seeders;

use App\Models\Article;
use App\Models\Comment;
use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Str;

class CommentSeeder extends Seeder
{
    public function run(): void
    {
        /*
        |--------------------------------------------------------------------------
        | 1. جلب المقالات المنشورة فقط
        |--------------------------------------------------------------------------
        */

        $articles = Article::where('status', 'published')->get();

        if ($articles->isEmpty()) {
            $this->command->error(
                'No published articles found. Seed articles first.'
            );

            return;
        }

        /*
        |--------------------------------------------------------------------------
        | 2. جلب المستخدمين النشطين
        |--------------------------------------------------------------------------
        |
        | بما أن التعليق يتطلب تسجيل دخول،
        | كل تعليق لازم يكون مرتبط بـ user_id.
        |
        */

        $users = User::where('status', 'active')->get();

        if ($users->isEmpty()) {
            $this->command->error(
                'No active users found. Seed users first.'
            );

            return;
        }

        /*
        |--------------------------------------------------------------------------
        | 3. المستخدم المسؤول عن اعتماد التعليقات
        |--------------------------------------------------------------------------
        */

        $approver = $users->first();

        /*
        |--------------------------------------------------------------------------
        | 4. محتوى التعليقات
        |--------------------------------------------------------------------------
        */

        $comments = [

            // =====================================================
            // Approved - 20
            // =====================================================

            'مقال رائع ومفيد جدًا، شكرًا على هذا المحتوى.',

            'أسلوب الطرح جميل وواضح، واستمتعت بقراءة المقال.',

            'موضوع مهم جدًا، خصوصًا في الوقت الحالي.',

            'أعجبني تبسيط الفكرة وطريقة شرحها بدون تعقيد.',

            'محتوى مميز، أتمنى نشر المزيد من المواضيع المشابهة.',

            'لفتت انتباهي عدة نقاط في المقال، خصوصًا الجزء الأخير.',

            'طرح متوازن ومفيد ويعطي القارئ صورة واضحة عن الموضوع.',

            'شكرًا للكاتب، المقال خفيف وسهل القراءة وفيه فائدة حقيقية.',

            'من أجمل المقالات التي قرأتها في هذا الموضوع مؤخرًا.',

            'أعجبني الربط بين الفكرة والواقع اليومي.',

            'المقال منظم وواضح، وأسلوب الكتابة مريح جدًا.',

            'أتفق مع أغلب النقاط المطروحة في المقال.',

            'موضوع يستحق القراءة فعلًا، استفدت من المعلومات المذكورة.',

            'أتمنى مقالًا ثانيًا يكمل هذا الموضوع بتفاصيل أكثر.',

            'الشرح بسيط ومباشر، وهذا أكثر شيء أعجبني.',

            'أعجبني أن المقال لا يكتفي بعرض الفكرة بل يوضح أثرها أيضًا.',

            'محتوى ثري ومناسب جدًا للقارئ غير المتخصص.',

            'فكرة جميلة، وأعتقد أنها تستحق نقاشًا أوسع.',

            'قراءة ممتعة، شكرًا على الاهتمام بجودة المحتوى.',

            'المقال أعطاني زاوية جديدة للنظر إلى الموضوع.',


            // =====================================================
            // Pending - 6
            // =====================================================

            'موضوع جميل، عندي بعض الأسئلة حول النقاط المذكورة.',

            'هل يمكن التوسع أكثر في هذا الموضوع في مقال قادم؟',

            'أتمنى إضافة أمثلة أكثر في الجزء الأخير من المقال.',

            'أعتقد أن بعض النقاط تحتاج إلى شرح أكبر.',

            'لدي تجربة مختلفة قليلًا مع هذا الموضوع وأحببت مشاركتها.',

            'مقال جيد، وأتمنى رؤية الجزء الثاني قريبًا.',


            // =====================================================
            // Rejected - 4
            // =====================================================

            'هذا تعليق تجريبي سيتم رفضه.',

            'تعليق مكرر للاختبار فقط.',

            'محتوى غير مناسب للاختبار.',

            'تعليق مرفوض لتجربة لوحة إدارة التعليقات.',
        ];

        /*
        |--------------------------------------------------------------------------
        | 5. إنشاء التعليقات
        |--------------------------------------------------------------------------
        */

        foreach ($comments as $index => $content) {

            /*
            |--------------------------------------------------------------------------
            | تحديد حالة التعليق
            |--------------------------------------------------------------------------
            |
            | 0 - 19  => approved
            | 20 - 25 => pending
            | 26 - 29 => rejected
            |
            */

            if ($index < 20) {

                $status = 'approved';

            } elseif ($index < 26) {

                $status = 'pending';

            } else {

                $status = 'rejected';
            }

            /*
            |--------------------------------------------------------------------------
            | توزيع التعليقات على المقالات المنشورة
            |--------------------------------------------------------------------------
            */

            $article = $articles[
                $index % $articles->count()
            ];

            /*
            |--------------------------------------------------------------------------
            | توزيع المستخدمين على التعليقات
            |--------------------------------------------------------------------------
            */

            $user = $users[
                $index % $users->count()
            ];

            /*
            |--------------------------------------------------------------------------
            | إنشاء التعليق
            |--------------------------------------------------------------------------
            */

            Comment::create([
                'uuid' => (string) Str::uuid(),

                'article_id' => $article->id,

                /*
                 * النظام لا يدعم الردود على التعليقات.
                 */
                'parent_id' => null,

                /*
                 * التعليق من مستخدم مسجل دخول.
                 */
                'user_id' => $user->id,

                /*
                 * Guest comments غير مستخدمة في النظام.
                 */
                'guest_name' => null,
                'guest_email' => null,
                'guest_website' => null,

                'content' => $content,

                'ip_address' => '127.0.0.1',

                'user_agent' => 'Seeder',

                'status' => $status,

                /*
                 * فقط التعليقات المقبولة لها approved_by.
                 */
                'approved_by' =>
                    $status === 'approved'
                        ? $approver->id
                        : null,

                /*
                 * فقط التعليقات المقبولة لها approved_at.
                 */
                'approved_at' =>
                    $status === 'approved'
                        ? now()
                            ->subDays(rand(0, 10))
                            ->subHours(rand(0, 23))
                        : null,

                'created_at' =>
                    now()
                        ->subDays(rand(0, 20))
                        ->subHours(rand(0, 23)),

                'updated_at' => now(),
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | 6. رسالة النجاح
        |--------------------------------------------------------------------------
        */

        $this->command->info(
            'Comments seeded successfully.'
        );

        $this->command->info(
            'Total comments: 30'
        );

        $this->command->info(
            'Approved comments: 20'
        );

        $this->command->info(
            'Pending comments: 6'
        );

        $this->command->info(
            'Rejected comments: 4'
        );
    }
}